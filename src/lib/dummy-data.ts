export function getArticleBySlug(slug: string): Article | undefined {
  return ARTICLES.find((a) => a.slug === slug);
}

export function getCategoryBySlug(slug: string): Category | undefined {
  return CATEGORIES.find((c) => c.slug === slug);
}

export function getCategoryName(slug: string): string {
  return categoryName(slug);
}

export function getArticlesByCategory(slug: string): Article[] {
  return sortByNewest(ARTICLES.filter((a) => a.categorySlug === slug));
}

export function getRelatedArticles(article: Article): Article[] {
  return article.relatedSlugs
    .map((s) => getArticleBySlug(s))
    .filter((a): a is Article => Boolean(a));
}

export function sortByNewest(list: Article[]): Article[] {
  return [...list].sort((a, b) => (a.publishedAt < b.publishedAt ? 1 : -1));
}

export const ALL_ARTICLES_NEWEST = sortByNewest(ARTICLES);
